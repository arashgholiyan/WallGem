import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:wall_gem/domain/entities/wallpaper.dart';
import 'package:wall_gem/presentation/widgets/palette/palette_export_modal.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const testWallpaper = Wallpaper(
    id: 'wp_palette_1',
    title: 'Neon Synth City',
    author: 'Kavinsky',
    sourceName: 'Wallhaven',
    thumbUrl: 'https://example.com/thumb.jpg',
    fullUrl: 'https://example.com/full.jpg',
    resolution: '3840x2160',
    aspectRatio: '16:9',
    category: 'Cyberpunk',
    dominantColors: [
      Color(0xFFFF0055), // Vivid Pink #FF0055
      Color(0xFF00FFCC), // Neon Cyan #00FFCC
      Color(0xFF8800FF), // Violet    #8800FF
    ],
  );

  Widget buildModalTestWidget({Wallpaper wallpaper = testWallpaper}) {
    return MaterialApp(
      home: Scaffold(
        body: Center(child: PaletteExportModal(wallpaper: wallpaper)),
      ),
    );
  }

  setUp(() {
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(SystemChannels.platform, null);
  });

  testWidgets(
    'PaletteExportModal renders dialog header, title, and color swatches',
    (WidgetTester tester) async {
      tester.view.physicalSize = const Size(1280, 800);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);

      await tester.pumpWidget(buildModalTestWidget());

      expect(find.text('Dynamic Palette Exporter'), findsOneWidget);
      expect(find.text('Neon Synth City'), findsOneWidget);
      expect(find.text('🎨'), findsOneWidget);

      // Verify all 3 color hex labels are rendered
      expect(find.text('#FF0055'), findsOneWidget);
      expect(find.text('#00FFCC'), findsOneWidget);
      expect(find.text('#8800FF'), findsOneWidget);
    },
  );

  testWidgets(
    'PaletteExportModal defaults to Pywal format and displays Pywal Xresources preview',
    (WidgetTester tester) async {
      tester.view.physicalSize = const Size(1280, 800);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);

      await tester.pumpWidget(buildModalTestWidget());

      final selectableTextFinder = find.byType(SelectableText);
      expect(selectableTextFinder, findsOneWidget);

      final preview = tester.widget<SelectableText>(selectableTextFinder).data!;
      expect(
        preview,
        contains('! Generated by Wall Gem Dynamic Palette Exporter'),
      );
      expect(preview, contains('*background: #FF0055'));
      expect(preview, contains('*foreground: #F8FAFC'));
      expect(preview, contains('*color0: #0B0F19'));
      expect(preview, contains('*color1: #FF0055'));
      expect(preview, contains('*color2: #00FFCC'));
      expect(preview, contains('*color3: #8800FF'));
    },
  );

  testWidgets(
    'PaletteExportModal switches to CSS Variables format on chip tap',
    (WidgetTester tester) async {
      tester.view.physicalSize = const Size(1280, 800);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);

      await tester.pumpWidget(buildModalTestWidget());

      // Ensure visible and tap 'CSS Variables' chip
      await tester.ensureVisible(find.text('CSS Variables'));
      await tester.tap(find.text('CSS Variables'));
      await tester.pumpAndSettle();

      final preview = tester
          .widget<SelectableText>(find.byType(SelectableText))
          .data!;
      expect(
        preview,
        contains('/* Generated by Wall Gem Dynamic Palette Exporter */'),
      );
      expect(preview, contains(':root {'));
      expect(preview, contains('  --wg-bg: #0b0f19;'));
      expect(preview, contains('  --wg-accent-1: #ff0055;'));
      expect(preview, contains('  --wg-accent-2: #00ffcc;'));
      expect(preview, contains('  --wg-accent-3: #8800ff;'));
      expect(preview, contains('}'));
    },
  );

  testWidgets(
    'PaletteExportModal switches to JSON Palette format on chip tap',
    (WidgetTester tester) async {
      tester.view.physicalSize = const Size(1280, 800);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);

      await tester.pumpWidget(buildModalTestWidget());

      // Ensure visible and tap 'JSON Palette' chip
      await tester.ensureVisible(find.text('JSON Palette'));
      await tester.tap(find.text('JSON Palette'));
      await tester.pumpAndSettle();

      final preview = tester
          .widget<SelectableText>(find.byType(SelectableText))
          .data!;
      expect(preview, contains('"generator": "Wall Gem"'));
      expect(preview, contains('"version": "1.2.0"'));
      expect(preview, contains('"palette": ['));
      expect(preview, contains('"#ff0055"'));
      expect(preview, contains('"#00ffcc"'));
      expect(preview, contains('"#8800ff"'));
    },
  );

  testWidgets('PaletteExportModal switches to Hex CSV format on chip tap', (
    WidgetTester tester,
  ) async {
    tester.view.physicalSize = const Size(1280, 800);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.resetPhysicalSize);

    await tester.pumpWidget(buildModalTestWidget());

    // Ensure visible and tap 'Hex CSV' chip
    await tester.ensureVisible(find.text('Hex CSV'));
    await tester.tap(find.text('Hex CSV'));
    await tester.pumpAndSettle();

    final preview = tester
        .widget<SelectableText>(find.byType(SelectableText))
        .data!;
    expect(preview, equals('#FF0055, #00FFCC, #8800FF'));
  });

  testWidgets(
    'PaletteExportModal copies code snippet to clipboard and updates button state',
    (WidgetTester tester) async {
      tester.view.physicalSize = const Size(1280, 800);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);

      // Mock clipboard handling
      String? copiedClipboardContent;
      TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
          .setMockMethodCallHandler(SystemChannels.platform, (
            MethodCall methodCall,
          ) async {
            if (methodCall.method == 'Clipboard.setData') {
              copiedClipboardContent =
                  (methodCall.arguments as Map)['text'] as String?;
              return null;
            } else if (methodCall.method == 'Clipboard.getData') {
              return {'text': copiedClipboardContent};
            }
            return null;
          });

      await tester.pumpWidget(buildModalTestWidget());

      // Switch to Hex CSV format
      await tester.ensureVisible(find.text('Hex CSV'));
      await tester.tap(find.text('Hex CSV'));
      await tester.pumpAndSettle();

      // Tap Copy to Clipboard
      final copyButtonFinder = find.text('Copy to Clipboard');
      expect(copyButtonFinder, findsOneWidget);
      await tester.tap(copyButtonFinder);
      await tester.pump();

      // Verify copied state feedback
      expect(find.text('Copied to Clipboard!'), findsOneWidget);
      expect(find.byIcon(Icons.check), findsOneWidget);

      // Verify clipboard content
      expect(copiedClipboardContent, equals('#FF0055, #00FFCC, #8800FF'));

      // Fast forward 2 seconds to complete delayed reset timer
      await tester.pump(const Duration(seconds: 2));
      expect(find.text('Copy to Clipboard'), findsOneWidget);
    },
  );

  testWidgets(
    'PaletteExportModal gracefully falls back to default palette when colors list is empty',
    (WidgetTester tester) async {
      tester.view.physicalSize = const Size(1280, 800);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);

      const wallpaperNoColors = Wallpaper(
        id: 'no_colors',
        title: 'Minimal Wallpaper',
        author: 'Unknown',
        sourceName: 'Curated',
        thumbUrl: 'https://example.com/thumb.jpg',
        fullUrl: 'https://example.com/full.jpg',
        resolution: '1920x1080',
        aspectRatio: '16:9',
        category: 'Minimal',
        dominantColors: [],
      );

      await tester.pumpWidget(
        buildModalTestWidget(wallpaper: wallpaperNoColors),
      );

      // Verify fallback palette swatches appear
      expect(find.text('#6366F1'), findsOneWidget);
      expect(find.text('#38BDF8'), findsOneWidget);
      expect(find.text('#10B981'), findsOneWidget);

      final preview = tester
          .widget<SelectableText>(find.byType(SelectableText))
          .data!;
      expect(preview, contains('*background: #6366F1'));
    },
  );

  testWidgets(
    'PaletteExportModal dismisses when close icon button is tapped via showDialog',
    (WidgetTester tester) async {
      tester.view.physicalSize = const Size(1280, 800);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(tester.view.resetPhysicalSize);

      await tester.pumpWidget(
        MaterialApp(
          home: Scaffold(
            body: Builder(
              builder: (context) => ElevatedButton(
                onPressed: () =>
                    PaletteExportModal.show(context, testWallpaper),
                child: const Text('Open Modal'),
              ),
            ),
          ),
        ),
      );

      // Open modal
      await tester.tap(find.text('Open Modal'));
      await tester.pumpAndSettle();

      expect(find.byType(PaletteExportModal), findsOneWidget);

      // Tap close button
      await tester.tap(find.byIcon(Icons.close));
      await tester.pumpAndSettle();

      expect(find.byType(PaletteExportModal), findsNothing);
    },
  );
}
