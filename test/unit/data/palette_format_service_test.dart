import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:wall_gem/data/services/palette_format_service.dart';

void main() {
  const sampleColors = [
    Color(0xFF6366F1), // Indigo
    Color(0xFF38BDF8), // Sky Blue
    Color(0xFF10B981), // Emerald
    Color(0xFFF59E0B), // Amber
    Color(0xFFEC4899), // Pink
  ];

  test('PaletteFormatService exports Pywal .Xresources format', () {
    final pywal = PaletteFormatService.toPywal(sampleColors);
    expect(pywal, contains('! Generated by Wall Gem'));
    expect(pywal, contains('*background: #6366F1'));
    expect(pywal, contains('*color1: #6366F1'));
    expect(pywal, contains('*color2: #38BDF8'));
    expect(pywal, contains('*color3: #10B981'));
  });

  test('PaletteFormatService exports CSS root variables format', () {
    final css = PaletteFormatService.toCssVariables(sampleColors);
    expect(css, contains(':root {'));
    expect(css, contains('--wg-accent-1: #6366f1;'));
    expect(css, contains('--wg-accent-2: #38bdf8;'));
  });

  test('PaletteFormatService exports JSON format', () {
    final jsonStr = PaletteFormatService.toJson(sampleColors);
    expect(jsonStr, contains('"palette"'));
    expect(jsonStr, contains('#6366f1'));
    expect(jsonStr, contains('#38bdf8'));
  });

  test('PaletteFormatService exports Hex CSV format', () {
    final hexCsv = PaletteFormatService.toHexCsv(sampleColors);
    expect(hexCsv, contains('#6366F1, #38BDF8, #10B981'));
  });

  test('PaletteFormatService handles empty color list with elegant fallback', () {
    final pywal = PaletteFormatService.toPywal(const []);
    expect(pywal, isNotEmpty);
    expect(pywal, contains('*background: #'));

    final css = PaletteFormatService.toCssVariables(const []);
    expect(css, contains('--wg-accent-1: #'));
  });
}
