import 'dart:convert';
import 'package:flutter/material.dart';

/// Service responsible for exporting color palettes into popular format syntaxes,
/// including Pywal (.Xresources), CSS root custom properties, JSON, and Hex CSV.
class PaletteFormatService {
  static const List<Color> fallbackPalette = [
    Color(0xFF6366F1), // Indigo
    Color(0xFF38BDF8), // Sky Blue
    Color(0xFF10B981), // Emerald
    Color(0xFFF59E0B), // Amber
    Color(0xFFEC4899), // Pink
  ];

  static String _toHexUpper(Color color) {
    return '#${(color.toARGB32() & 0x00FFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';
  }

  static String _toHexLower(Color color) {
    return '#${(color.toARGB32() & 0x00FFFFFF).toRadixString(16).padLeft(6, '0').toLowerCase()}';
  }

  /// Exports color palette to Pywal (.Xresources) syntax.
  static String toPywal(List<Color> colors) {
    final active = colors.isEmpty ? fallbackPalette : colors;
    final buffer = StringBuffer();
    buffer.writeln('! Generated by Wall Gem Dynamic Palette Exporter');
    buffer.writeln('*background: ${_toHexUpper(active.first)}');
    buffer.writeln('*foreground: #F8FAFC');

    buffer.writeln('*color0: #0B0F19');
    for (int i = 1; i <= 15; i++) {
      final color = active[(i - 1) % active.length];
      buffer.writeln('*color$i: ${_toHexUpper(color)}');
    }
    return buffer.toString();
  }

  /// Exports color palette to CSS custom properties in a `:root` block.
  static String toCssVariables(List<Color> colors) {
    final active = colors.isEmpty ? fallbackPalette : colors;
    final buffer = StringBuffer();
    buffer.writeln('/* Generated by Wall Gem Dynamic Palette Exporter */');
    buffer.writeln(':root {');
    buffer.writeln('  --wg-bg: #0b0f19;');
    buffer.writeln('  --wg-surface: #1e293b;');
    buffer.writeln('  --wg-fg: #f8fafc;');
    for (int i = 0; i < active.length; i++) {
      buffer.writeln('  --wg-accent-${i + 1}: ${_toHexLower(active[i])};');
    }
    buffer.writeln('}');
    return buffer.toString();
  }

  /// Exports color palette to JSON format.
  static String toJson(List<Color> colors) {
    final active = colors.isEmpty ? fallbackPalette : colors;
    final map = {
      'generator': 'Wall Gem',
      'version': '1.2.0',
      'palette': active.map(_toHexLower).toList(),
      'exportedAt': DateTime.now().toIso8601String(),
    };
    return const JsonEncoder.withIndent('  ').convert(map);
  }

  /// Exports color palette to comma-separated hex strings.
  static String toHexCsv(List<Color> colors) {
    final active = colors.isEmpty ? fallbackPalette : colors;
    return active.map(_toHexUpper).join(', ');
  }
}
